import { readFile, mkdir, writeFile } from 'node:fs/promises'
const output = new URL('../packages/shared/src/generated.ts', import.meta.url)
await mkdir(new URL('../packages/shared/src/', import.meta.url), { recursive: true })
let source = '// Generated by scripts/artifacts.ts from actual Forge artifacts. Do not edit.\n'
for (const name of ['CipherBid','LocalCollectible']) {
  const artifact = JSON.parse(await readFile(new URL(`../contracts/out/${name}.sol/${name}.json`,import.meta.url),'utf8'))
  source += `export const ${name === 'CipherBid' ? 'auctionAbi' : 'collectibleAbi'} = ${JSON.stringify(artifact.abi,null,2)} as const\n`
}
await writeFile(output,source)
console.log('Generated shared ABIs from Forge artifacts.')
